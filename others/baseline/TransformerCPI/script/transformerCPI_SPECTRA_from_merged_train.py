def load_all_labels(shard_glob):
    print("🔍 Loading labels from all shards...", flush=True)
    labels = []
    shard_paths = sorted(glob.glob(shard_glob))
    
    if not shard_paths:
        raise FileNotFoundError(f"No shard files found matching: {shard_glob}")
    
    print(f"📁 Found {len(shard_paths)} shard files:", flush=True)
    for i, p in enumerate(shard_paths):
        print(f"  {i+1}. {os.path.basename(p)}")
    
    total_samples = 0
    for i, p in enumerate(shard_paths):
        print(f"📖 Loading shard {i+1}/{len(shard_paths)}: {os.path.basename(p)}", flush=True)
        start_time = time.time()
        
        with gzip.open(p, "rb") as f:
            data = pickle.load(f)
        
        shard_samples = 0
        for _, _, _, y in data:
            try:
                labels.append(int(y.item() if hasattr(y, "item") else int(y)))
                shard_samples += 1
            except Exception as e:
                print(f"⚠️  Warning: Failed to process label {y}, error: {e}")
                labels.append(int(y))
                shard_samples += 1
        
        total_samples += shard_samples
        elapsed = time.time() - start_time
        print(f"   ✅ Loaded {shard_samples} samples in {elapsed:.2f}s", flush=True)
    
    print(f"🎯 Total samples loaded: {total_samples}", flush=True)
    print(f"📊 Label distribution: {dict(zip(*np.unique(labels, return_counts=True)))}", flush=True)
    return labels, shard_paths

# ====== Iterable dataset filtering samples by id_set ======
from torch.utils.data import IterableDataset, DataLoader

class ShardedPickleIterableFiltered(IterableDataset):
    def __init__(self, shard_paths, id_set, device, shuffle_shards=False):
        self.shard_paths = list(shard_paths)
        self.id_set = id_set
        self.device = device
        self.shuffle_shards = shuffle_shards
        print(f"📦 Dataset created: {len(self.id_set)} samples from {len(self.shard_paths)} shards")

    def __iter__(self):
        # Shuffle the shard order if requested
        shard_paths = self.shard_paths.copy()
        if self.shuffle_shards:
            random.shuffle(shard_paths)
            
        gid = 0  # Global sample index, increasing across shards
        yielded_count = 0
        
        for shard_idx, p in enumerate(shard_paths):
            # print(f"🔄 Processing shard {shard_idx+1}/{len(shard_paths)}")
            with gzip.open(p, "rb") as f:
                data = pickle.load(f)
            
            for atom, adj, protein, label in data:
                if gid in self.id_set:
                    # Convert stored fp16/uint8 arrays to float32/long
                    yield (atom.float(), adj.float(), protein.float(), label.long())
                    yielded_count += 1
                    
                    # Print progress every 1000 samples
                    if yielded_count % 1000 == 0:
                        print(f"   📈 Yielded {yielded_count}/{len(self.id_set)} samples",flush=True)
                
                gid += 1

        print(f"   ✅ Finished yielding {yielded_count} samples for current split.", flush=True)
        if yielded_count != len(self.id_set):
            print(f"⚠️  Mismatch: yielded {yielded_count} != expected {len(self.id_set)}", flush=True)

def make_collate_fn(device):
    def _collate(batch):
        atoms, adjs, prots, labels = zip(*batch)
        return pack(list(atoms), list(adjs), list(prots), list(labels), device)
    return _collate

# ====== Train one epoch using a DataLoader ======
def train_one_epoch(model, optimizer, train_loader, epoch, fold):
    model.train()
    epoch_loss = 0.0
    batch_count = 0
    start_time = time.time()
    
    print(f"🚀 Training Fold {fold}, Epoch {epoch}...",flush=True)
    
    for batch_idx, data_pack in enumerate(train_loader):
        # Clear gradients through the model
        model.zero_grad(set_to_none=True)

        loss = model(data_pack)
        loss.backward()
        optimizer.step()

        epoch_loss += loss.item()
        batch_count += 1
        
        # Print progress every 100 batches
        if (batch_idx + 1) % 100 == 0:
            elapsed = time.time() - start_time
            avg_loss = epoch_loss / batch_count
            print(f"   📊 Batch {batch_idx + 1}: avg_loss={avg_loss:.6f}, time={elapsed:.1f}s")
    
    if batch_count == 0:
        print("⚠️  WARNING: No batches processed in training!")
        return 0.0
        
    avg_epoch_loss = epoch_loss / batch_count
    elapsed = time.time() - start_time
    print(f"✅ Training completed: {batch_count} batches, avg_loss={avg_epoch_loss:.6f}, time={elapsed:.1f}s")
    
    return avg_epoch_loss

