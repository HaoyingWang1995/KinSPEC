from sklearn.metrics import roc_auc_score, precision_recall_curve, auc

def eval_auc_prc(model, dev_loader, fold, epoch):
    print(f"📋 Evaluating Fold {fold}, Epoch {epoch}...")
    model.eval()
    T, S = [], []
    batch_count = 0
    start_time = time.time()
    
    with torch.no_grad():
        for batch_idx, data_pack in enumerate(dev_loader):
            correct_labels, predicted_labels, predicted_scores = model(data_pack, train=False)
            T.extend(correct_labels)
            S.extend(predicted_scores)
            batch_count += 1
            
            # Print progress every 50 batches
            if (batch_idx + 1) % 50 == 0:
                elapsed = time.time() - start_time
                print(f"   📊 Eval Batch {batch_idx + 1}: samples={len(T)}, time={elapsed:.1f}s")
    
    if len(T) == 0:
        print("⚠️  WARNING: No samples processed in evaluation!")
        return 0.0, 0.0
        
    AUC = roc_auc_score(T, S) if len(set(T)) > 1 else 0.0
    prec, reca, _ = precision_recall_curve(T, S)
    PRC = auc(reca, prec)
    
    elapsed = time.time() - start_time
    print(f"✅ Evaluation completed: {len(T)} samples, AUC={AUC:.6f}, PRC={PRC:.6f}, time={elapsed:.1f}s")
    
    return AUC, PRC

