    out_csv = f"{res_dir}/result/SPECTRA_{band_range}_VSDS_eval.csv"
    os.makedirs(os.path.dirname(out_csv), exist_ok=True)
    pd.DataFrame([{
        "ROC_AUC": auc_roc,
        "PR_AUC": prc,
        "BEDROC_alpha80_5": bedroc,
        **ef_dict,
    }]).to_csv(out_csv, index=False)
    print(f"[VSDS] metrics saved to {out_csv}")

    print(f"[VSDS] ROC-AUC = {auc_roc:.6f} | PR-AUC = {prc:.6f}")
    return auc_roc, prc,ef_dict


